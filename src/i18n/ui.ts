export const ui: Record<Lang, Dict> = { fr, en, es };
export const t = (lang: Lang) => ui[lang];

const months: Record<Lang, string[]> = {
  fr: ['janvier', 'février', 'mars', 'avril', 'mai', 'juin', 'juillet', 'août', 'septembre', 'octobre', 'novembre', 'décembre'],
  en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
  es: ['enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio', 'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre'],
};

export function formatDate(iso: string, lang: Lang) {
  const [y, m, d] = iso.split('-').map(Number);
  const month = months[lang][m - 1];
  if (lang === 'es') return `${d} de ${month} de ${y}`;
  return `${d} ${month} ${y}`;
}

/** Office times: "8 h" in French, "8 am" in English, "8:00 a. m." in Spanish. */
export function formatTime(hhmm: string, lang: Lang) {
  const [h, m] = hhmm.split(':').map(Number);
  const mm = String(m).padStart(2, '0');
  if (lang === 'fr') return `${h} h${m ? mm : ''}`;
  const h12 = h % 12 === 0 ? 12 : h % 12;
  if (lang === 'es') return `${h12}:${mm} ${h >= 12 ? 'p. m.' : 'a. m.'}`;
  return `${h12}${m ? ':' + mm : ''} ${h >= 12 ? 'pm' : 'am'}`;
}

/** French typography: non-breaking space before ? ! : ; and inside guillemets. */
export function typo(text: string, lang: Lang) {
  // Keep form and visa codes such as K-1, IR-1, I-129F or DS-160 from breaking at the hyphen.
  const codes = text.replace(/\b([A-Z]{1,2})-(\d)/g, '$1-⁠$2');
  if (lang !== 'fr') return codes;
  return codes.replace(/ ([?!:;»])/g, ' $1').replace(/« /g, '« ');
}
